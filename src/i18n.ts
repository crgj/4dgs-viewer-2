let currentLanguage: Language = readInitialLanguage();
const listeners = new Set<(language: Language) => void>();

// #WDD-gpt 2026-06-13 - 语言状态保存在浏览器 localStorage，刷新页面后继续沿用
function readStoredLanguage(): Language | null {
    try {
        const stored = window.localStorage?.getItem(STORAGE_KEY);
        return stored === 'zh' || stored === 'en' ? stored : null;
    } catch {
        return null;
    }
}

function writeStoredLanguage(language: Language) {
    try {
        window.localStorage?.setItem(STORAGE_KEY, language);
    } catch {
        // Storage may be unavailable in private or restricted browser modes.
    }
}

function readInitialLanguage(): Language {
    return readStoredLanguage() ?? 'en';
}

export function getLanguage() {
    return currentLanguage;
}

export function t(key: string, vars?: Record<string, string | number>) {
    const value = translations[currentLanguage][key] ?? translations.en[key] ?? key;
    if (!vars) return value;
    return value.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}

export function setLanguage(language: Language) {
    currentLanguage = language;
    writeStoredLanguage(language);
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
    applyI18n();
    listeners.forEach((listener) => listener(language));
}

export function toggleLanguage() {
    setLanguage(currentLanguage === 'en' ? 'zh' : 'en');
}

export function onLanguageChange(listener: (language: Language) => void) {
    listeners.add(listener);
    return () => listeners.delete(listener);
}

export function applyI18n(root: ParentNode = document) {
    if (root === document) {
        const titleKey = document.documentElement.dataset.i18nTitle || document.body?.dataset.i18nTitle || 'app.title';
        document.title = t(titleKey);
        document.documentElement.lang = currentLanguage === 'zh' ? 'zh-CN' : 'en';
    }

    root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
        el.textContent = t(el.dataset.i18n || '');
    });
    root.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach((el) => {
        el.innerHTML = t(el.dataset.i18nHtml || '');
    });

    const attrNames = ['aria-label', 'data-tip', 'title', 'placeholder'];
    for (const attr of attrNames) {
        const dataName = `i18n${attr.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join('')}`;
        root.querySelectorAll<HTMLElement>(`[data-${dataName.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`)}]`).forEach((el) => {
            const key = el.dataset[dataName];
            if (key) el.setAttribute(attr, t(key));
        });
    }
}

export function bindLanguageToggle(button: HTMLElement | null) {
    if (!button) return;
    button.addEventListener('click', () => toggleLanguage());
}
